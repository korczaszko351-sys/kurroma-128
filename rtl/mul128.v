// ============================================================================
// mul128 : 128x128 -> 256 bit, dekompozycja na 4 limb-y po 32 bity
// 16 mnozen 32x32->64. W pelni kombinacyjny.
// ============================================================================
`include "kurroma_defs.vh"

module mul128 (
    input  wire [127:0] a,
    input  wire [127:0] b,
    output wire [255:0] p
);
    wire [31:0] a0 = a[31:0];
    wire [31:0] a1 = a[63:32];
    wire [31:0] a2 = a[95:64];
    wire [31:0] a3 = a[127:96];
    wire [31:0] b0 = b[31:0];
    wire [31:0] b1 = b[63:32];
    wire [31:0] b2 = b[95:64];
    wire [31:0] b3 = b[127:96];

    wire [63:0] p00 = a0 * b0;
    wire [63:0] p01 = a0 * b1;
    wire [63:0] p02 = a0 * b2;
    wire [63:0] p03 = a0 * b3;
    wire [63:0] p10 = a1 * b0;
    wire [63:0] p11 = a1 * b1;
    wire [63:0] p12 = a1 * b2;
    wire [63:0] p13 = a1 * b3;
    wire [63:0] p20 = a2 * b0;
    wire [63:0] p21 = a2 * b1;
    wire [63:0] p22 = a2 * b2;
    wire [63:0] p23 = a2 * b3;
    wire [63:0] p30 = a3 * b0;
    wire [63:0] p31 = a3 * b1;
    wire [63:0] p32 = a3 * b2;
    wire [63:0] p33 = a3 * b3;

    wire [255:0] s0 = {{192{1'b0}}, p00};
    wire [255:0] s1 = {{160{1'b0}}, p01, 32'd0} + {{160{1'b0}}, p10, 32'd0};
    wire [255:0] s2 = {{128{1'b0}}, p02, 64'd0} + {{128{1'b0}}, p11, 64'd0} + {{128{1'b0}}, p20, 64'd0};
    wire [255:0] s3 = {{96{1'b0}}, p03, 96'd0} + {{96{1'b0}}, p12, 96'd0}
                   + {{96{1'b0}}, p21, 96'd0} + {{96{1'b0}}, p30, 96'd0};
    wire [255:0] s4 = {{64{1'b0}}, p13, 128'd0} + {{64{1'b0}}, p22, 128'd0} + {{64{1'b0}}, p31, 128'd0};
    wire [255:0] s5 = {{32{1'b0}}, p23, 160'd0} + {{32{1'b0}}, p32, 160'd0};
    wire [255:0] s6 = {p33, 192'd0};

    assign p = s0 + s1 + s2 + s3 + s4 + s5 + s6;
endmodule
